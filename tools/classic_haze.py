"""Validate authored map haze settings and generate the add-on's static table."""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / 'config/classic-enhanced/haze-maps.json'
HEADER = ROOT / 'tools/classic_haze_profiles.h'


def load(path=CONFIG):
    data = json.loads(path.read_text(encoding='utf-8'))
    if data.get('schema') != 1:
        raise ValueError('unsupported haze schema')
    names = set()
    for profile in data['profiles']:
        name = profile['map']
        if not name or not all(c.isascii() and (c.isalnum() or c == '_') for c in name) or name.lower() in names:
            raise ValueError('invalid or duplicate map name')
        names.add(name.lower())
        cap = profile['opacity_cap']
        if not math.isfinite(cap) or not 0 <= cap <= .72 or len(profile['pockets']) > 2:
            raise ValueError('invalid opacity or pocket count')
        for p in profile['pockets']:
            for field in ('center', 'radii', 'color'):
                if len(p[field]) != 3 or not all(math.isfinite(v) for v in p[field]):
                    raise ValueError('invalid pocket vector')
            if not all(100 <= v <= 150000 for v in p['radii']):
                raise ValueError('invalid pocket radii')
            if not all(0 <= v <= 1 for v in p['color']) or not math.isfinite(p['density']) or not 0 <= p['density'] <= 1:
                raise ValueError('invalid pocket color/density')
    return data


def render(data):
    def vector(values):
        return '{' + ','.join(f'{float(v):.8f}f' for v in values) + '}'
    rows = []
    for p in data['profiles']:
        pockets = ['{' + ','.join([vector(c['center']), vector(c['radii']), vector(c['color'] + [c['density']])]) + '}' for c in p['pockets']]
        rows.append(' {"%s",%s,%d,{%s}},' % (p['map'], f"{p['opacity_cap']:.8f}f", len(pockets), ','.join(pockets)))
    return '''// Generated by tools/classic_haze.py from config/classic-enhanced/haze-maps.json.
// Original experimental art settings; not recovered native nebula definitions.
#pragma once
struct HazePocket {float center[3],radii[3],color_density[4];};
struct HazeProfile {const char *map;float opacity_cap;unsigned count;HazePocket pockets[2];};
static const HazeProfile haze_profiles[]={
''' + '\n'.join(rows) + '''
};
static bool haze_name_equal(const char *a,const char *b){
 if(!a || !b)return false;
 while(*a && *b){char x=*a++,y=*b++;if(x>='A' && x<='Z')x+=32;if(y>='A' && y<='Z')y+=32;if(x!=y)return false;}
 return *a==*b;
}
static const HazeProfile *select_haze_profile(const char *map,bool offline){
 if(!map || !*map)return nullptr;
 // The pinned client ships one offline scenario, Curt3, on CTF_arena.
 if(offline && haze_name_equal(map,"CTF_arena"))map="Curt3";
 if(haze_name_equal(map,"jrmap292.trn"))map="JRMAP";
 for(const auto &profile:haze_profiles)if(haze_name_equal(map,profile.map))return &profile;
 return nullptr;
}
'''


def verify_generated():
    if HEADER.read_text(encoding='utf-8') != render(load()):
        raise ValueError('haze table is stale; run python -I tools/classic_haze.py')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        verify_generated()
    else:
        HEADER.write_text(render(load()), encoding='utf-8')
    print('Map haze profiles verified.' if args.check else 'Generated map haze profiles.')
