"""Generate tools/vessel_combat.py: per-vessel simple HP and gun damage (findings 9.46).

Usage: python -I tools/make_vessel_combat.py work/2.9.2/sco.json evidence/2.9.2/gun_table.json tools/vessel_combat.py

sco.json comes from tools/sco_dump.py (AoAObjects.odb export). For every
fighter the in-flight menu offers (station_stub.SELECTABLE_VESSELS):
  * simple_hp: the first Shield system's hit points. A live 2.9.2 client gave
    a loaded Ym Khtat simple HP (+0x1E8/+0x1EC) 107, its Shield value.
  * guns: client gun system index -> per-shot damage. The index a client
    reports (gun +0xA4) is the system's position in the .Sco list plus one:
    a live Ym Khtat reported 2..7 for its six guns at positions 1..6. The
    level comes from the weapon id (G-310 -> id 310), or from the system name
    when the id is empty (Gun-360); damage is the gun table's field +6.
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import station_stub  # noqa: E402

GUN = 12
SHIELD = 4


def gun_damage(table):
    return {g["id"]: g["fields"]["damage (obj+0x11A)"] for g in table["guns"]}


def level_id(system):
    for text in (system.get("weapon") or "", system.get("name") or ""):
        digits = re.findall(r"\d{3}", text)
        if digits:
            return int(digits[-1])
    return None


def build(sco, table):
    damage = gun_damage(table)
    objects = sco if isinstance(sco, list) else sco.get("objects", sco)
    if isinstance(objects, dict):
        objects = list(objects.values())
    by_name = {o["name"]: o for o in objects if isinstance(o, dict) and "name" in o}
    out = {}
    for vessel in sorted(station_stub.SELECTABLE_VESSELS):
        systems = by_name[vessel].get("systems", [])
        shields = [s["hp"] for s in systems if s.get("type") == SHIELD]
        guns = {}
        for position, system in enumerate(systems):
            if system.get("type") == GUN and damage.get(level_id(system)) is not None:
                guns[position + 1] = damage[level_id(system)]
        out[vessel] = (shields[0] if shields else 0.0, guns)
    return out


def main():
    sco, table, target = (Path(a) for a in sys.argv[1:4])
    data = build(json.loads(sco.read_text(encoding="utf-8")), json.loads(table.read_text(encoding="utf-8")))
    lines = ['"""Generated by tools/make_vessel_combat.py; do not edit (findings 9.46).',
             "",
             "VESSELS[name] = (simple HP, {client gun system index: per-shot gun-table damage}).",
             '"""', "VESSELS = {"]
    for vessel, (hp, guns) in data.items():
        lines.append(f"    {vessel!r}: ({hp!r}, {guns!r}),")
    lines.append("}")
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(data)} vessels -> {target}")


if __name__ == "__main__":
    main()
