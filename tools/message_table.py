"""Merge dispatch tables and send sites into one message-ID table (Markdown).

Usage: python -I tools/message_table.py <out.md>

Inputs (all produced by the other tools):
  evidence/2.7.1/dispatch_4d1830.json   CAOAComm receive switch
  evidence/2.7.1/dispatch_45b430.json   CClientComm::ReceiveExtraPacket switch
  evidence/2.7.1/send_sites.json        immediate type/length stores
  evidence/2.7.1/packet_sizes.json      compiled structure-size diagnostics
  evidence/2.9.2/dispatch_base.json, dispatch_extra.json, send_sites.json

"Size hint" lists diagnostic structure names whose compiled size equals the
2.7.1 send length. It is a hint only and is marked unique when exactly one
structure has that size.
"""
import json
import sys
from pathlib import Path


def load(p):
    return json.loads(Path(p).read_text(encoding="utf-8"))


def handlers(*paths):
    out = {}
    for p in paths:
        for c in load(p)["cases"]:
            if not c["is_default"]:
                out[c["type"]] = f"{Path(p).stem.replace('dispatch_', '')}@{c['target']}"
    return out


def sends(p):
    out = {}
    for s in load(p)["sites"]:
        out.setdefault(s["type"], {"lengths": set(), "sites": 0})
        out[s["type"]]["lengths"].add(s["length"])
        out[s["type"]]["sites"] += 1
    return out


def main():
    out = sys.argv[1]
    r271 = handlers("evidence/2.7.1/dispatch_4d1830.json", "evidence/2.7.1/dispatch_45b430.json")
    r292 = handlers("evidence/2.9.2/dispatch_base.json", "evidence/2.9.2/dispatch_extra.json")
    s271, s292 = sends("evidence/2.7.1/send_sites.json"), sends("evidence/2.9.2/send_sites.json")
    by_size = {}
    for r in load("evidence/2.7.1/packet_sizes.json")["rows"]:
        by_size.setdefault(r["value"], []).append(r["name"])
    types = sorted(set(r271) | set(r292) | set(s271) | set(s292))

    def fmt_len(d, t):
        if t not in d:
            return ""
        ls = sorted("?" if x is None else str(x) for x in d[t]["lengths"])
        return ",".join(ls) + (f" ({d[t]['sites']} sites)" if d[t]["sites"] > 1 else "")

    lines = [
        "# AoA message-type table (static)",
        "",
        "Generated by `tools/message_table.py` from the dispatch and send-site evidence.",
        "Type = the u8 carried in the datagram trailer (`CComm` packet object +0x498).",
        "",
        "* **Recv** columns: switch@case-address handling an incoming type (see the",
        "  dispatch_*.json evidence for the calls made by each case).",
        "* **Send len** columns: payload length paired with an immediate type store;",
        "  `?` = no immediate length nearby; blank = no immediate type store found",
        "  (the type may still be sent through code this heuristic does not see).",
        "* **Size hint** (2.7.1 only): compiled `sizeof` diagnostics equal to the send",
        "  length. A hint, not a confirmed name; `=` marks a unique size match.",
        "",
        "| Type | Recv 2.7.1 | Recv 2.9.2 | Send len 2.7.1 | Send len 2.9.2 | Size hint (2.7.1) |",
        "|---|---|---|---|---|---|",
    ]
    for t in types:
        hint = ""
        if t in s271:
            names = set()
            for ln in s271[t]["lengths"]:
                names.update(by_size.get(ln, []))
            if len(names) == 1:
                hint = "= " + next(iter(names))
            elif names:
                hint = " / ".join(sorted(names)[:4]) + (" ..." if len(names) > 4 else "")
        lines.append(f"| 0x{t:02x} ({t}) | {r271.get(t, '')} | {r292.get(t, '')} | "
                     f"{fmt_len(s271, t)} | {fmt_len(s292, t)} | {hint} |")
    lines += ["", f"Types: {len(types)} total; received 2.7.1 {len(r271)}, 2.9.2 {len(r292)}; "
              f"sent (immediate sites) 2.7.1 {len(s271)}, 2.9.2 {len(s292)}.", ""]
    Path(out).write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}: {len(types)} types")


if __name__ == "__main__":
    main()
