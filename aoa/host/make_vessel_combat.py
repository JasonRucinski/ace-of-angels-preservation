"""Generate aoa/host/vessel_combat.py: per-vessel simple HP and gun damage (findings 9.46).

Usage: python -I tools/run.py aoa.host.make_vessel_combat work/2.9.2/sco.json evidence/2.9.2/gun_table.json [aoa/host/vessel_combat.py]
       python -I tools/run.py aoa.host.make_vessel_combat --check work/2.9.2/sco.json evidence/2.9.2/gun_table.json

--check regenerates in memory and exits 1 with a diff when the committed
file differs; it writes nothing.

sco.json comes from aoa/formats/sco.py (AoAObjects.odb export). For every
fighter the in-flight menu offers (station_runtime.SELECTABLE_VESSELS):
  * simple_hp: the first Shield system's hit points. A live 2.9.2 client gave
    a loaded Ym Khtat simple HP (+0x1E8/+0x1EC) 107, its Shield value.
  * guns: client gun system index -> per-shot damage. The index a client
    reports (gun +0xA4) is the system's position in the .Sco list plus one:
    a live Ym Khtat reported 2..7 for its six guns at positions 1..6. The
    level comes from the weapon id (G-310 -> id 310), or from the system name
    when the id is empty (Gun-360); damage is the gun table's field +6.
"""
import argparse
import difflib
import json
import re
import sys
from pathlib import Path

from aoa.host.runtime import SELECTABLE_VESSELS  # noqa: E402

TARGET = Path(__file__).resolve().with_name("vessel_combat.py")

GUN = 12
SHIELD = 4


def gun_damage(table):
    return {g["id"]: g["fields"]["damage (obj+0x11A)"] for g in table["guns"]}


def level_id(system):
    for text in (system.get("weapon") or "", system.get("name") or ""):
        digits = re.findall(r"\d{3}", text)
        if digits:
            return int(digits[-1])
    return None


def build(sco, table):
    damage = gun_damage(table)
    objects = sco if isinstance(sco, list) else sco.get("objects", sco)
    if isinstance(objects, dict):
        objects = list(objects.values())
    by_name = {o["name"]: o for o in objects if isinstance(o, dict) and "name" in o}
    out = {}
    for vessel in sorted(SELECTABLE_VESSELS):
        systems = by_name[vessel].get("systems", [])
        shields = [s["hp"] for s in systems if s.get("type") == SHIELD]
        guns = {}
        for position, system in enumerate(systems):
            if system.get("type") == GUN and damage.get(level_id(system)) is not None:
                guns[position + 1] = damage[level_id(system)]
        out[vessel] = (shields[0] if shields else 0.0, guns)
    return out


def render(data):
    lines = ['"""Generated by aoa/host/make_vessel_combat.py; do not edit (findings 9.46).',
             "",
             "VESSELS[name] = (simple HP, {client gun system index: per-shot gun-table damage}).",
             '"""', "VESSELS = {"]
    for vessel, (hp, guns) in data.items():
        lines.append(f"    {vessel!r}: ({hp!r}, {guns!r}),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("sco", type=Path, help="sco.json from aoa/formats/sco.py")
    parser.add_argument("table", type=Path, help="evidence/2.9.2/gun_table.json")
    parser.add_argument("target", type=Path, nargs="?", default=TARGET, help="default aoa/host/vessel_combat.py")
    parser.add_argument("--check", action="store_true", help="compare with target instead of writing it")
    args = parser.parse_args(argv)
    try:
        data = build(json.loads(args.sco.read_text(encoding="utf-8")),
                     json.loads(args.table.read_text(encoding="utf-8")))
        text = render(data)
        if args.check:
            current = args.target.read_text(encoding="utf-8")
            if current == text:
                print(f"{args.target} matches its generator ({len(data)} vessels)")
                return 0
            sys.stdout.writelines(difflib.unified_diff(current.splitlines(True), text.splitlines(True),
                                                       str(args.target), "regenerated"))
            return 1
    except (OSError, ValueError, KeyError) as error:
        parser.exit(2, f"{parser.prog}: error: {error}\n")
    args.target.write_text(text, encoding="utf-8")
    print(f"{len(data)} vessels -> {args.target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
