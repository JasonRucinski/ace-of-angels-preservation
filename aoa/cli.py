"""Shared command-line conventions for the tools in this folder.

Every tool has `main(argv=None)` built on `parser()`, does no work at import,
and ends with

    if __name__ == "__main__":
        sys.exit(cli_util.run(main))

so `--help` only prints usage, and a missing or unreadable input ends with one
line on stderr and a non-zero exit instead of a traceback.
"""
import argparse
import sys
from pathlib import Path

from aoa.paths import ROOT
WORK = ROOT / "work"


def parser(doc, **kwargs):
    """An ArgumentParser whose help shows the module docstring as written."""
    kwargs.setdefault("formatter_class", argparse.RawDescriptionHelpFormatter)
    return argparse.ArgumentParser(description=doc, **kwargs)


def output_dir(value):
    """argparse type for an output folder: refuses a name that looks like an option."""
    if not value or value.startswith("-"):
        raise argparse.ArgumentTypeError(f"refusing output folder {value!r}: give a real folder name")
    return value


def add_evidence_option(ap, committed):
    """--evidence PATH for an audit whose committed copy is `committed` (repo-relative).

    Without it the audit writes to work/<committed>, so a re-run never
    overwrites committed evidence by accident.
    """
    ap.add_argument("--evidence", type=Path, metavar="PATH",
                    help=f"write the result to PATH instead of work/{committed} "
                         f"(the committed copy is {committed})")


def evidence_target(chosen, committed):
    """The --evidence PATH if given, else work/<committed>; its parent folder is created."""
    target = Path(chosen) if chosen else WORK / committed
    target.parent.mkdir(parents=True, exist_ok=True)
    return target


def shown(path):
    """A path for messages: repo-relative when inside the repository."""
    path = Path(path).resolve()
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def run(main, argv=None):
    """Call main(argv); turn a missing or unreadable file into a one-line error."""
    try:
        return main(argv)
    except (FileNotFoundError, IsADirectoryError, NotADirectoryError, PermissionError) as error:
        name = Path(sys.argv[0]).name if sys.argv and sys.argv[0] else "tool"
        detail = error.strerror or str(error)
        where = f": {error.filename}" if error.filename else ""
        sys.exit(f"{name}: error: {detail}{where}")


class DocBlock:
    """A table in a Markdown doc that a module generates, between two marker comments.

    The text around the markers is written by hand. `main()` gives the
    generator its command line: print the block, --check (exit 1 when the
    committed block is stale) or --write (replace it). A test compares
    `current()` with the file, so a stale table fails CI.
    """

    def __init__(self, doc, what, module, render):
        self.path = ROOT / doc
        self.doc, self.module, self.render = doc, module, render
        self.begin = f"<!-- {what}: generated by python -I tools/run.py {module} --write; do not edit by hand -->"
        self.end = f"<!-- end of generated {what} -->"

    def splice(self, text, block=None):
        """`text` with the generated block replaced by `block` (default: a fresh render)."""
        try:
            start = text.index(self.begin) + len(self.begin)
            end = text.index(self.end, start)
        except ValueError:
            raise SystemExit(f"{self.doc}: missing the generated-table markers") from None
        return text[:start] + "\n\n" + (self.render() if block is None else block) + "\n" + text[end:]

    def committed(self):
        return self.path.read_text(encoding="utf-8")

    def current(self):
        """The doc as it should be: the committed text with a fresh block."""
        return self.splice(self.committed())

    def main(self, argv, doc):
        ap = parser(doc)
        mode = ap.add_mutually_exclusive_group()
        mode.add_argument("--check", action="store_true", help=f"exit 1 if the table in {self.doc} is out of date")
        mode.add_argument("--write", action="store_true", help=f"rewrite the table in {self.doc}")
        a = ap.parse_args(argv)
        if not (a.check or a.write):
            sys.stdout.write(self.render())
            return 0
        text = self.committed()
        updated = self.splice(text)
        if a.check:
            if updated != text:
                print(f"{self.doc}: the generated table is out of date; "
                      f"run python -I tools/run.py {self.module} --write", file=sys.stderr)
                return 1
            return 0
        if updated != text:
            self.path.write_text(updated, encoding="utf-8", newline="\n")
            print(f"wrote {self.doc}")
        return 0
